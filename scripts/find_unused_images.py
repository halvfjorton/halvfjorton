#!/usr/bin/env python3
"""List image files under assets/ not referenced by the built site."""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD_PY = ROOT / "scripts" / "build.py"
IMAGE_SUFFIXES = {".webp", ".jpg", ".jpeg", ".png", ".svg", ".gif", ".ico"}
SKIP_PREFIXES = ("docs/", "proposals/")


def human_size(num: int) -> str:
    if num < 1024:
        return f"{num} B"
    if num < 1024**2:
        return f"{num / 1024:.1f} KiB"
    return f"{num / 1024**2:.1f} MiB"


def gallery_stems_from_build() -> set[str]:
    text = BUILD_PY.read_text(encoding="utf-8")
    block = re.search(
        r"GALLERY_STEMS_800_1600\s*=\s*frozenset\(\s*\{([^}]+)\}",
        text,
        re.DOTALL,
    )
    stems: set[str] = set()
    if block:
        for line in block.group(1).splitlines():
            m = re.search(r'"([^"]+)"', line)
            if m:
                stems.add(m.group(1))
    return stems


def gallery_variants_for_stem(stem: str, stems_800_1600: set[str]) -> list[str]:
    base = f"/assets/img/gallery/{stem}"
    if stem in stems_800_1600:
        return [f"{base}-800w.webp", f"{base}-1600w.webp"]
    return [
        f"{base}-480w.webp",
        f"{base}-800w.webp",
        f"{base}-1200w.webp",
        f"{base}-1920w.webp",
    ]


def paths_from_build_py() -> set[str]:
    text = BUILD_PY.read_text(encoding="utf-8")
    return set(re.findall(r"/assets/img/[A-Za-z0-9_./-]+", text))


def paths_from_manifest_used_on_site(corpus: str) -> set[str]:
    """Manifest paths that also appear in HTML/CSS/JS (not the full auto inventory)."""
    manifest = ROOT / "assets" / "cms" / "image-manifest.json"
    if not manifest.is_file():
        return set()
    data = json.loads(manifest.read_text(encoding="utf-8"))
    used: set[str] = set()
    for entry in data.get("images", []):
        paths = [entry.get("default", "")]
        paths.extend(entry.get("variants", {}).values())
        srcset = entry.get("srcset") or ""
        for part in srcset.split(","):
            part = part.strip()
            if part:
                paths.append(part.split()[0])
        for p in paths:
            if p and p in corpus:
                used.add(p)
    return used


def collect_reference_corpus() -> str:
    parts: list[str] = []
    for path in ROOT.glob("**/*.html"):
        if "home/" in path.as_posix():
            continue
        parts.append(path.read_text(encoding="utf-8", errors="replace"))
    for path in ROOT.glob("assets/**/*.css"):
        parts.append(path.read_text(encoding="utf-8", errors="replace"))
    for path in ROOT.glob("assets/**/*.js"):
        parts.append(path.read_text(encoding="utf-8", errors="replace"))
    org = ROOT / "assets" / "schema" / "organization.json"
    if org.is_file():
        parts.append(org.read_text(encoding="utf-8", errors="replace"))

    parts.extend(paths_from_build_py())
    stems_800 = gallery_stems_from_build()
    for stem in stems_800:
        parts.extend(gallery_variants_for_stem(stem, stems_800))

    base = "\n".join(parts)
    parts.extend(paths_from_manifest_used_on_site(base))
    return "\n".join(parts)


def is_referenced(rel_path: str, corpus: str) -> bool:
    posix = rel_path.replace("\\", "/")
    candidates = {posix, f"/{posix}", Path(posix).name}
    for c in candidates:
        if c in corpus:
            return True
    name = Path(posix).name
    stem = Path(name).stem
    stem_base = re.sub(r"-\d+w$", "", stem)
    stem_base = re.sub(r"-hero$", "", stem_base)
    for c in (stem, stem_base, f"gallery/{stem_base}"):
        if c in corpus:
            return True
    return False


def main() -> int:
    corpus = collect_reference_corpus()
    unused: list[tuple[str, int]] = []
    for path in sorted(ROOT.rglob("*")):
        if not path.is_file():
            continue
        if path.suffix.lower() not in IMAGE_SUFFIXES:
            continue
        rel = path.relative_to(ROOT).as_posix()
        if rel.startswith(SKIP_PREFIXES):
            continue
        if not rel.startswith("assets/"):
            continue
        if not is_referenced(rel, corpus):
            unused.append((rel, path.stat().st_size))

    lines = [
        "# Unused images",
        "",
        "Generated by `python3 scripts/find_unused_images.py` after `python3 scripts/build.py`.",
        "",
        "An image is **unused** when it is not referenced in:",
        "",
        "- Built HTML (excluding `home/`, which is source-only)",
        "- `assets/**/*.css` and `assets/**/*.js`",
        "- `scripts/build.py` (including expanded `GALLERY_STEMS_800_1600` variants)",
        "- `assets/cms/image-manifest.json` entries that also appear in the HTML/CSS/JS corpus",
        "",
        "`image-manifest.json` is generated for CMS mode and lists every file under "
        "`assets/img/`; this report ignores manifest-only listings so you can see what the "
        "**live site** does not load.",
        "",
        f"**Total:** {len(unused)} files, "
        f"{human_size(sum(s for _, s in unused))} combined.",
        "",
        "| Path | Size |",
        "| --- | ---: |",
    ]
    for rel, size in unused:
        lines.append(f"| `{rel}` | {human_size(size)} |")

    out = ROOT / "UNUSED_IMAGES.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out} ({len(unused)} unused images)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
