#!/usr/bin/env python3
"""List image files under assets/ not referenced by the built site output."""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
IMAGE_SUFFIXES = {".webp", ".jpg", ".jpeg", ".png", ".svg", ".gif", ".ico"}
SKIP_PREFIXES = ("docs/", "proposals/")


def human_size(num: int) -> str:
    if num < 1024:
        return f"{num} B"
    if num < 1024**2:
        return f"{num / 1024:.1f} KiB"
    return f"{num / 1024**2:.1f} MiB"


_ASSET_IMG_RE = re.compile(r"/assets/img/[A-Za-z0-9_./-]+")


def referenced_asset_paths() -> set[str]:
    parts: list[str] = []
    for path in ROOT.glob("**/*.html"):
        if "home/" in path.as_posix():
            continue
        parts.append(path.read_text(encoding="utf-8", errors="replace"))
    for path in ROOT.glob("assets/**/*.css"):
        parts.append(path.read_text(encoding="utf-8", errors="replace"))
    for path in ROOT.glob("assets/**/*.js"):
        parts.append(path.read_text(encoding="utf-8", errors="replace"))
    org = ROOT / "assets" / "schema" / "organization.json"
    if org.is_file():
        parts.append(org.read_text(encoding="utf-8", errors="replace"))
    corpus = "\n".join(parts)
    refs: set[str] = set()
    for m in _ASSET_IMG_RE.finditer(corpus):
        refs.add(m.group(0).lstrip("/"))
    for m in re.finditer(r"https://halvfjorton\.se/assets/img/[A-Za-z0-9_./-]+", corpus):
        refs.add(m.group(0).replace("https://halvfjorton.se/", ""))
    return refs


def is_referenced(rel_path: str, refs: set[str]) -> bool:
    posix = rel_path.replace("\\", "/")
    if posix in refs:
        return True
    name = Path(posix).name
    return any(r.endswith("/" + name) or r == name for r in refs)


def main() -> int:
    refs = referenced_asset_paths()
    unused: list[tuple[str, int]] = []
    for path in sorted(ROOT.rglob("*")):
        if not path.is_file():
            continue
        if path.suffix.lower() not in IMAGE_SUFFIXES:
            continue
        rel = path.relative_to(ROOT).as_posix()
        if rel.startswith(SKIP_PREFIXES):
            continue
        if not rel.startswith("assets/"):
            continue
        if not is_referenced(rel, refs):
            unused.append((rel, path.stat().st_size))

    lines = [
        "# Unused images",
        "",
        "Generated by `python3 scripts/find_unused_images.py` after `python3 scripts/build.py`.",
        "",
        "References are taken only from **built site output**: HTML (excluding `home/`), "
        "`assets/**/*.css`, `assets/**/*.js`, and `assets/schema/organization.json`.",
        "",
    ]
    if not unused:
        lines.extend(
            [
                "**No unused images in the repo.** Removed assets are archived by the site owner "
                "(see Dropbox / `halvfjorton-alla-oanvanda-bilder.zip` from migration).",
                "",
            ]
        )
    else:
        lines.extend(
            [
                f"**Total:** {len(unused)} files, "
                f"{human_size(sum(s for _, s in unused))} combined.",
                "",
                "| Path | Size |",
                "| --- | ---: |",
            ]
        )
        for rel, size in unused:
            lines.append(f"| `{rel}` | {human_size(size)} |")

    out = ROOT / "UNUSED_IMAGES.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out} ({len(unused)} unused images)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
